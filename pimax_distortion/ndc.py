# pyright: strict

from typing import TYPE_CHECKING, Any, overload, Tuple, TypeVar

if TYPE_CHECKING:
    import numpy as np

    _IntegerT = TypeVar('_IntegerT', bound=np.integer)
    _IntegerT2 = TypeVar('_IntegerT2', bound=np.integer)
    _FloatingT = TypeVar('_FloatingT', bound=np.floating)
    _FloatingT2 = TypeVar('_FloatingT2', bound=np.floating)
    _NDArray = TypeVar('_NDArray', bound=np.ndarray[tuple[Any, ...]])
    _FloatingNDArray = TypeVar('_FloatingNDArray', bound=np.ndarray[tuple[Any, ...], np.dtype[np.floating]])


@overload
def to_ndc(x: int) -> int: ...
@overload
def to_ndc(x: float) -> float: ...
@overload
def to_ndc(x: _IntegerT) -> _IntegerT: ...
@overload
def to_ndc(x: _FloatingT) -> _FloatingT: ...
@overload
def to_ndc(x: _NDArray) -> _NDArray: ...

def to_ndc(x):  # pyright: ignore[reportUnknownParameterType]
    return (x * 2) - 1  # pyright: ignore[reportUnknownVariableType]


@overload
def to_ndc_uv(u: int, v: int) -> Tuple[int, int]: ...
@overload
def to_ndc_uv(u: float, v: int) -> Tuple[float, int]: ...
@overload
def to_ndc_uv(u: _IntegerT, v: int) -> Tuple[_IntegerT, int]: ...
@overload
def to_ndc_uv(u: _FloatingT, v: int) -> Tuple[_FloatingT, int]: ...
@overload
def to_ndc_uv(u: int, v: float) -> Tuple[int, float]: ...
@overload
def to_ndc_uv(u: float, v: float) -> Tuple[float, float]: ...
@overload
def to_ndc_uv(u: _IntegerT, v: float) -> Tuple[_IntegerT, float]: ...
@overload
def to_ndc_uv(u: _FloatingT, v: float) -> Tuple[_FloatingT, float]: ...
@overload
def to_ndc_uv(u: int, v: _IntegerT) -> Tuple[int, _IntegerT]: ...
@overload
def to_ndc_uv(u: float, v: _IntegerT) -> Tuple[float, _IntegerT]: ...
@overload
def to_ndc_uv(u: _IntegerT, v: _IntegerT2) -> Tuple[_IntegerT, _IntegerT2]: ...
@overload
def to_ndc_uv(u: _FloatingT, v: _IntegerT) -> Tuple[_FloatingT, _IntegerT]: ...
@overload
def to_ndc_uv(u: int, v: _FloatingT) -> Tuple[int, _FloatingT]: ...
@overload
def to_ndc_uv(u: float, v: _FloatingT) -> Tuple[float, _FloatingT]: ...
@overload
def to_ndc_uv(u: _IntegerT, v: _FloatingT) -> Tuple[_IntegerT, _FloatingT]: ...
@overload
def to_ndc_uv(u: _FloatingT, v: _FloatingT2) -> Tuple[_FloatingT, _FloatingT2]: ...

def to_ndc_uv(u, v):  # pyright: ignore[reportInconsistentOverload]
    ru = to_ndc(u)  # pyright: ignore[reportUnknownArgumentType]
    rv = to_ndc(v)  # pyright: ignore[reportUnknownArgumentType]
    return ru, rv


@overload
def from_ndc(x: int | float) -> float: ...
@overload
def from_ndc(x: np.integer) -> np.float64: ...
@overload
def from_ndc(x: _FloatingT) -> _FloatingT: ...
@overload
def from_ndc(x: np.ndarray[tuple[Any, ...], np.dtype[np.integer]]) -> np.ndarray[tuple[Any, ...], np.dtype[np.float64]]: ...
@overload
def from_ndc(x: _FloatingNDArray) -> _FloatingNDArray: ...

def from_ndc(x):  # pyright: ignore[reportUnknownParameterType]
    return (x + 1) / 2  # pyright: ignore[reportUnknownVariableType]


@overload
def from_ndc_uv(u: int | float, v: int | float) -> Tuple[float, float]: ...
@overload
def from_ndc_uv(u: np.integer, v: int | float) -> Tuple[np.float64, float]: ...
@overload
def from_ndc_uv(u: _FloatingT, v: int | float) -> Tuple[_FloatingT, float]: ...
@overload
def from_ndc_uv(u: int | float, v: np.integer) -> Tuple[float, np.float64]: ...
@overload
def from_ndc_uv(u: np.integer, v: np.integer) -> Tuple[np.float64, np.float64]: ...
@overload
def from_ndc_uv(u: _FloatingT, v: np.integer) -> Tuple[_FloatingT, np.float64]: ...
@overload
def from_ndc_uv(u: int | float, v: _FloatingT) -> Tuple[float, _FloatingT]: ...
@overload
def from_ndc_uv(u: np.integer, v: _FloatingT) -> Tuple[np.float64, _FloatingT]: ...
@overload
def from_ndc_uv(u: _FloatingT, v: _FloatingT2) -> Tuple[_FloatingT, _FloatingT2]: ...

def from_ndc_uv(u, v):  # pyright: ignore[reportUnknownParameterType]
    ru = from_ndc(u)  # pyright: ignore[reportUnknownVariableType, reportUnknownArgumentType]
    rv = from_ndc(v)  # pyright: ignore[reportUnknownVariableType, reportUnknownArgumentType]
    return ru, rv  # pyright: ignore[reportUnknownVariableType]
